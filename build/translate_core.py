def _is_keep(tok):
    t = tok.strip().lower().strip(".,;:!?()[]{}'\"")
    if t in KEEP:
        return True
    if re.fullmatch(r"[a-z]+[0-9]+", t):  # fbx2020 etc
        return False
    if re.fullmatch(r"[a-z]{1,3}[0-9]+", t):
        return True
    if "." in tok and tok.lower().endswith(EXT):
        return True
    if re.fullmatch(r"[a-z]+://[^\s]+", tok.lower()):  # url
        return True
    return False


def _split_camel(s):
    # Node_LightShape -> [Node, Light, Shape]; camelCase too
    parts = re.findall(r"[A-Z]?[a-z0-9]+|[A-Z]+(?![a-z])", s)
    return parts


def _translate_token(tok):
    if tok == "":
        return ""
    low = tok.lower()
    if _is_keep(tok):
        return tok
    if low in WORD:
        return WORD[low]
    if tok in PHRASE:
        return PHRASE[tok]
    if low in PHRASE:
        return PHRASE[low]
    # CamelCase / underscore split
    if re.search(r"[A-Z]", tok) or "_" in tok:
        segs = re.split(r"[_\s]+", tok)
        out = []
        for seg in segs:
            sub = _split_camel(seg)
            zh = "".join(WORD.get(s.lower(), s) for s in sub) if sub else seg
            # if any sub unknown, keep original seg
            if any(WORD.get(s.lower(), s) == s for s in sub) and len(sub) > 1:
                # partial; preserve unknown parts
                zh = "".join(WORD.get(s.lower(), s) for s in sub)
            out.append(zh)
        return "".join(out)
    # trailing punctuation preserved
    m = re.match(r"^(.*?)([.,;:!?]+)$", tok)
    if m:
        return _translate_token(m.group(1)) + m.group(2)
    return tok


def _core(text):
    """翻译纯文本(无占位符)"""
    text = text.strip()
    if not text:
        return ""
    if text in PHRASE:
        return PHRASE[text]
    # 处理 "X and Y" / "X or Y"
    text2 = re.sub(r"\band\b", " 和 ", text, flags=re.I)
    text2 = re.sub(r"\bor\b", " 或 ", text2, flags=re.I)
    # 标点：英文冒号转中文冒号（仅当后无空格的标签场景）
    tokens = re.split(r"(\s+)", text2)
    out = []
    for tok in tokens:
        if tok.strip() == "":
            out.append("")
            continue
        out.append(_translate_token(tok))
    res = "".join(out)
    # 清理多余空格（中文间不应有空格），但保留英文与中文间适度空格已由拼接决定
    res = re.sub(r"([一-鿿]) +([一-鿿])", r"\1\2", res)
    return res.strip()


def translate(text):
    """翻译任意英文 UI 文本，保留 {n} 占位符"""
    if text is None:
        return None
    if not isinstance(text, str):
        return text
    text = text.strip()
    if text == "":
        return ""
    # 提取占位符 {0} {1} 等
    placeholders = re.findall(r"\{[^}]*\}", text)
    tmp = re.sub(r"\{[^}]*\}", "\x00", text)
    zh = _core(tmp)
    # 还原占位符
    for ph in placeholders:
        zh = zh.replace("\x00", ph, 1)
    return zh


